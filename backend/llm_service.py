"""
backend/llm_service.py
CardioSense: Google Gemini Orchestration and Tool Calling Service.

Connects Google Gemini with the existing CardioSense Machine Learning prediction tool.
Preserves the trained ML model as the sole authority for predictions and SHAP scores.
The LLM serves as an explainable, plain-language clinical communicator.
"""

import os
import sys
import logging
from pathlib import Path
from typing import Dict, Any, Optional, List

# Ensure backend directory is in sys.path
_BACKEND_DIR = Path(__file__).resolve().parent
if str(_BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(_BACKEND_DIR))

# Load backend/.env if present without overriding existing system env vars
from dotenv import load_dotenv
_ENV_FILE = _BACKEND_DIR / ".env"
if _ENV_FILE.exists():
    load_dotenv(dotenv_path=_ENV_FILE, override=False)

from google import genai
from google.genai import types

from llm_tools import predict_heart_disease_severity

logger = logging.getLogger("cardiosense_llm_service")

# Clinical and educational disclaimer
DISCLAIMER_TEXT = (
    "CardioSense is an AI-powered educational and research tool designed to demonstrate "
    "explainable Machine Learning in cardiovascular risk pattern assessment. It is NOT a "
    "medical device and does NOT provide medical diagnosis, clinical prognosis, or treatment "
    "recommendations. Always consult a qualified healthcare professional for medical advice."
)

# System instruction strictly governing Gemini's behavior and boundaries
SYSTEM_INSTRUCTION = """You are the CardioSense Clinical Assistant, an intelligent, empathetic, and responsible AI companion for an explainable heart disease severity prediction system.

You work in tandem with a trained Machine Learning model (Random Forest trained on clinical reference data) and an explainable AI system (SHAP - SHapley Additive exPlanations).

YOUR CORE RESPONSIBILITIES & BOUNDARIES:

1. EXPLAINER, NOT A DIAGNOSTICIAN:
   - You are an explainer and educator. You are NOT a doctor and do NOT provide medical diagnoses, treatment prescriptions, or definitive medical verdicts.
   - Always state that this assessment is generated by a Machine Learning pattern-recognition model for educational and informational purposes, and strongly encourage consulting a qualified healthcare professional.

2. TOOL CALLING RULE:
   - When a user asks to predict, estimate, assess, or check heart disease severity, or provides clinical parameters (such as age, blood pressure, cholesterol, ECG, chest pain, etc.), you MUST call the `predict_heart_disease_severity` tool.
   - Clinical parameter mapping: Map 'ST depression' or 'Exercise ST depression' to the `oldpeak` (or `st_depression`) argument, 'maximum heart rate' to `thalach`, 'resting blood pressure' to `trestbps`, 'serum cholesterol' to `chol`, 'chest pain' to `cp`, 'fasting blood sugar' to `fbs`, 'resting ECG' to `restecg`, 'exercise-induced angina' to `exang`, 'ST slope' to `slope`, 'fluoroscopy vessels' to `ca`, and 'thalassemia' to `thal`.
   - Do NOT attempt to guess, predict, or invent severity classes, likelihood percentages, or SHAP feature attributions on your own. All predictions must come strictly from the tool execution.

3. HANDLING MISSING OR INVALID INPUTS:
   - If the tool returns `status: "missing_inputs"`, you must NOT invent or assume the missing values. Politely and clearly ask the user for the specific missing measurements, explaining briefly why each is needed.
   - If the tool returns `status: "validation_error"`, inform the user which specific numbers fall outside medically plausible bounds and ask them to verify those entries.

4. EXPLAINING VALID PREDICTIONS:
   - If the tool returns `status: "success"`, use the exact results from the tool:
     * State the predicted class and severity label (Class 0: No Disease, Class 1: Mild, Class 2: Moderate, Class 3: Severe, Class 4: Very Severe).
     * Mention the top class probabilities.
     * Translate the provided SHAP factors into simple, easy-to-understand language. Clearly highlight which factors increased predicted severity (risk contributors, e.g. elevated resting blood pressure, ST depression) and which factors decreased predicted severity (protective contributors, e.g. optimal cholesterol, high peak heart rate).
     * Never change, contradict, or round the numbers provided by the tool.

5. GENERAL INQUIRIES:
   - If the user asks general questions about cardiovascular health, CardioSense, how the system works, or what SHAP values are, answer informatively and helpfully WITHOUT calling the prediction tool.
"""


def get_api_key() -> Optional[str]:
    """Retrieves the Gemini API key from environment variables."""
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    return key if key else None


def is_gemini_configured() -> bool:
    """Checks whether a valid Gemini API key is configured."""
    key = get_api_key()
    return bool(key and key != "your_gemini_api_key_here")


def get_gemini_client(api_key: Optional[str] = None) -> genai.Client:
    """
    Creates and returns a Google Gemini client.
    Raises ValueError if API key is missing.
    """
    key = api_key or get_api_key()
    if not key or key == "your_gemini_api_key_here":
        raise ValueError(
            "GEMINI_API_KEY is not configured. Please create a `.env` file in the `backend/` "
            "directory with `GEMINI_API_KEY=your_actual_key` (obtained from https://aistudio.google.com)."
        )
    return genai.Client(api_key=key)


def _serialize_history(history: List[Any]) -> List[Dict[str, str]]:
    """Converts internal chat history objects into clean JSON-serializable dictionaries."""
    serialized: List[Dict[str, str]] = []
    for item in history:
        role = getattr(item, "role", "user")
        parts = getattr(item, "parts", [])
        texts = []
        for p in parts:
            text = getattr(p, "text", None)
            if text:
                texts.append(text)
        if texts:
            serialized.append({
                "role": "model" if role == "model" else "user",
                "content": "\n".join(texts),
            })
    return serialized


def _sanitize_error_message(msg: str) -> str:
    """Removes sensitive API keys or credentials from error strings."""
    if not msg:
        return ""
    import re
    sanitized = str(msg)
    api_key = os.environ.get("GEMINI_API_KEY")
    if api_key and api_key in sanitized:
        sanitized = sanitized.replace(api_key, "[REDACTED_API_KEY]")
    sanitized = re.sub(r"key=[A-Za-z0-9_\-\.]+", "key=[REDACTED]", sanitized)
    sanitized = re.sub(r"AIza[0-9A-Za-z_\-]{35}", "[REDACTED_API_KEY]", sanitized)
    sanitized = re.sub(r"AQ\.[A-Za-z0-9_\-\.]{20,}", "[REDACTED_API_KEY]", sanitized)
    return sanitized


def generate_response(
    user_message: str,
    conversation_history: Optional[List[Dict[str, Any]]] = None,
    model_name: Optional[str] = None,
    client: Optional[Any] = None,
    patient_inputs: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Core entrypoint for the CardioSense LLM interaction.

    Processes user input, orchestrates tool calling with the existing ML model,
    and returns a structured payload with both the raw ML prediction and the LLM explanation.

    Args:
        user_message: The prompt or clinical query from the user.
        conversation_history: Optional list of previous messages [{"role": "user"|"model", "content": "..."}].
        model_name: Optional Gemini model name override (defaults to GEMINI_MODEL env or gemini-2.5-flash).
        client: Optional pre-configured genai.Client (useful for testing and dependency injection).
        patient_inputs: Optional dictionary of verified patient inputs to guarantee accurate tool parameters.

    Returns:
        Structured response dictionary:
        {
            "success": bool,
            "status": "success" | "missing_inputs" | "validation_error" | "api_key_missing" | "error",
            "explanation": str,
            "ml_prediction": Optional[Dict[str, Any]],
            "tool_called": bool,
            "tool_status": "success" | "missing_inputs" | "validation_error" | "none",
            "tool_result": Optional[Dict[str, Any]],
            "disclaimer": str,
            "conversation_history": List[Dict[str, str]],
        }
    """
    # 1. Check if Gemini API key is configured before attempting network requests
    if client is None and not is_gemini_configured():
        logger.warning("Gemini API key is not configured. Request rejected gracefully.")
        return {
            "success": False,
            "status": "api_key_missing",
            "explanation": (
                "Google Gemini API key is not configured. "
                "To enable AI explanations, please create a `.env` file in the `backend/` directory with: "
                "GEMINI_API_KEY=your_actual_api_key_here "
                "(Get an API key from https://aistudio.google.com)."
            ),
            "ml_prediction": None,
            "tool_called": False,
            "tool_status": "none",
            "tool_result": None,
            "disclaimer": DISCLAIMER_TEXT,
            "conversation_history": conversation_history or [],
        }

    selected_model = model_name or os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")

    # 2. Format incoming conversation history into Gemini Content objects
    converted_history: List[types.Content] = []
    if conversation_history:
        for msg in conversation_history:
            role = msg.get("role", "user")
            content_role = "model" if role in ("assistant", "model") else "user"
            content_text = msg.get("content") or msg.get("text") or ""
            if content_text:
                converted_history.append(
                    types.Content(
                        role=content_role,
                        parts=[types.Part.from_text(text=str(content_text))],
                    )
                )

    # 3. Configure Gemini tool calling
    config = types.GenerateContentConfig(
        system_instruction=SYSTEM_INSTRUCTION,
        tools=[predict_heart_disease_severity],
        temperature=0.2,
        automatic_function_calling=types.AutomaticFunctionCallingConfig(disable=True),
    )

    try:
        active_client = client or get_gemini_client()
        chat = active_client.chats.create(
            model=selected_model,
            config=config,
            history=converted_history if converted_history else None,
        )

        # 4. Send the user message to Gemini
        initial_response = chat.send_message(user_message)

        tool_called = False
        tool_status = "none"
        tool_result: Optional[Dict[str, Any]] = None
        ml_prediction: Optional[Dict[str, Any]] = None
        final_text = ""

        # 5. Check if Gemini requested a tool execution
        if initial_response.function_calls:
            tool_called = True
            call = initial_response.function_calls[0]
            logger.info(f"Gemini requested tool call: {call.name} with args: {call.args}")

            # Security verification: only allow predict_heart_disease_severity
            if call.name != "predict_heart_disease_severity":
                tool_result = {
                    "status": "error",
                    "success": False,
                    "message": f"Unauthorized tool invocation requested: {call.name}",
                }
            else:
                raw_args = dict(call.args) if call.args else {}
                # If verified patient_inputs were provided from an existing assessment,
                # safely backfill any arguments that the LLM may have omitted or misnamed
                if patient_inputs and isinstance(patient_inputs, dict):
                    for k, v in patient_inputs.items():
                        if (k not in raw_args or raw_args[k] is None or raw_args[k] == "") and v is not None and v != "":
                            raw_args[k] = v

                # Call the existing Python prediction tool
                tool_result = predict_heart_disease_severity(**raw_args)

            tool_status = tool_result.get("status", "unknown")

            # Preserve the original ML output intact
            if tool_result.get("success") and "raw_ml_result" in tool_result:
                ml_prediction = tool_result["raw_ml_result"]

            # 6. Send the tool execution result back to Gemini
            tool_response_part = types.Part.from_function_response(
                name=call.name,
                response=tool_result,
            )
            follow_up_response = chat.send_message(tool_response_part)
            final_text = follow_up_response.text or ""
        else:
            # General conversation or inquiry without prediction
            final_text = initial_response.text or ""

        # Retrieve updated conversation history
        updated_history = _serialize_history(chat.get_history())

        return {
            "success": True,
            "status": "success" if tool_status in ("success", "none") else tool_status,
            "explanation": final_text,
            "ml_prediction": ml_prediction,
            "tool_called": tool_called,
            "tool_status": tool_status,
            "tool_result": tool_result,
            "disclaimer": DISCLAIMER_TEXT,
            "conversation_history": updated_history,
        }
 
    except Exception as e:
        raw_error_str = str(e)
        clean_error_str = _sanitize_error_message(raw_error_str)
        logger.error(f"Error during Gemini processing: {clean_error_str}")

        error_code = getattr(e, "code", None)
        error_status = str(getattr(e, "status", "")).upper()
        lower_error = raw_error_str.lower()
        upper_error = raw_error_str.upper()

        # Check for 503 / Model Overloaded / High Demand
        from google.genai.errors import APIError
        is_503 = (
            (isinstance(e, APIError) and (error_code == 503 or "503" in raw_error_str))
            or "high demand" in lower_error
            or "spikes in demand" in lower_error
            or "overloaded" in lower_error
            or (error_status == "UNAVAILABLE" and isinstance(e, APIError))
        )

        # Check for 429 / Quota / Rate Limit
        is_429 = (
            (isinstance(e, APIError) and (error_code == 429 or "429" in raw_error_str))
            or "RESOURCE_EXHAUSTED" in error_status
            or "quota exceeded" in lower_error
            or "rate limit" in lower_error
        )

        # Check for Invalid / Missing API Key
        is_auth_error = (
            (error_code in (401, 403))
            or "API_KEY_INVALID" in upper_error
            or "invalid api key" in lower_error
            or "unauthorized" in lower_error
        )

        if is_503:
            status = "service_unavailable"
            explanation = (
                "The Google Gemini model is currently experiencing high demand. "
                "Spikes in demand are usually temporary. "
                "Your Machine Learning severity prediction and SHAP analysis below are fully operational."
            )
        elif is_429:
            status = "rate_limit_exceeded"
            explanation = (
                "The Google Gemini API rate limit or request quota has been reached. "
                "Your Machine Learning severity prediction and SHAP analysis below remain active."
            )
        elif is_auth_error:
            status = "api_key_missing"
            explanation = (
                "The configured Gemini API key is invalid or unauthorized. "
                "Please verify your GEMINI_API_KEY in backend/.env."
            )
        else:
            status = "error"
            explanation = (
                "An unexpected error occurred while communicating with the AI service. "
                f"Error: {clean_error_str}"
            )

        return {
            "success": False,
            "status": status,
            "explanation": explanation,
            "ml_prediction": None,
            "tool_called": False,
            "tool_status": "error",
            "tool_result": None,
            "disclaimer": DISCLAIMER_TEXT,
            "conversation_history": conversation_history or [],
            "error_details": clean_error_str,
        }
